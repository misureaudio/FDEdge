function cfg = config(varargin)
% fdedge config factory - one struct of PoC-matching defaults per profile
% (single source of truth for the replays).
%   cfg = config('Profile','poc'|'beta'|'riesz'|'hybrid', 'field', value, ...)
% Every default is cited from the PoC it mirrors:
%   Profile 'poc'    (edge_fd_poc.m): Part A N=2048 (t = (0:N)' non-
%     normalized), alphas (0.40:0.05:0.95)', beta=0.7, sigA=0.01;
%     Part B M=1024, A=1, sGrid=8, sigB=0.02, nfr=60, xe0=0.25, v=0.01,
%     qV=1e-7 (2-state KF).
%   Profiles 'beta'/'riesz'/'hybrid' (edge_fd_beta_track.m /
%     edge_fd_riesz_track.m / edge_fd_hybrid_track.m): M=1024,
%     alphas (0.55:0.05:0.85)', A=1, sGrid=8, sigB=0.02, w0=0.03,
%     w1=0.28, win=0.02, xLo=0.17, xHi=0.83, qV=1e-8, qW=1e-12 (4-state
%     KF), nfr=40, xe0=0.20, v=0.01, b0=0.55, w=0.30/39.
%     'beta' adds ell=6 (slope-peak half-width); 'riesz' adds the probe
%     vectors dpr = linspace(0.03,0.13,11), dprw = linspace(0.025,0.12,11).
% D9 invariant (validated here): for beta/riesz/hybrid the probe window
% must start outside the Gaussian blur core: w0 > 3*sGrid/M.
if nargin == 0
    Profile = 'poc';
    ov = struct();
else
    if mod(numel(varargin), 2) ~= 0
        error('fdedge:config', 'name-value pairs must come in pairs');
    end
    ov = struct(varargin{:});
    if isfield(ov, 'Profile')
        Profile = ov.Profile;
    else
        Profile = 'poc';
    end
end
% Profile defaults (flat struct; all fields present for every profile -
% v0 test list: w0/w1 exist even for the one-sided profiles).
switch lower(Profile)
    case 'poc'
        cfg = struct( ...
            'Profile', 'poc', ...
            'M', 1024, 'N', 2048, ...
            'alphas', (0.40:0.05:0.95)', ...
            'beta', 0.70, ...
            'A', 1.0, 'sGrid', 8, ...
            'sigA', 0.01, 'sigB', 0.02, ...
            'w0', 0.03, 'w1', 0.28, ...
            'xLo', 0.17, 'xHi', 0.83, 'win', 0.02, ...
            'qV', 1e-7, 'qW', 1e-12, ...
            'ell', 6, ...
            'dpr', linspace(0.03,0.13,11), ...
            'dprw', linspace(0.025,0.12,11), ...
            'nfr', 60, 'xe0', 0.25, 'v', 0.01, 'b0', 0.55, 'w', 0.30/39);
    case 'beta'
        cfg = struct( ...
            'Profile', 'beta', ...
            'M', 1024, 'N', 2048, ...
            'alphas', (0.55:0.05:0.85)', ...
            'beta', 0.70, ...
            'A', 1.0, 'sGrid', 8, ...
            'sigA', 0.01, 'sigB', 0.02, ...
            'w0', 0.03, 'w1', 0.28, ...
            'xLo', 0.17, 'xHi', 0.83, 'win', 0.02, ...
            'qV', 1e-8, 'qW', 1e-12, ...
            'ell', 6, ...
            'dpr', linspace(0.03,0.13,11), ...
            'dprw', linspace(0.025,0.12,11), ...
            'nfr', 40, 'xe0', 0.20, 'v', 0.01, 'b0', 0.55, 'w', 0.30/39);
    case 'riesz'
        cfg = struct( ...
            'Profile', 'riesz', ...
            'M', 1024, 'N', 2048, ...
            'alphas', (0.55:0.05:0.85)', ...
            'beta', 0.70, ...
            'A', 1.0, 'sGrid', 8, ...
            'sigA', 0.01, 'sigB', 0.02, ...
            'w0', 0.03, 'w1', 0.28, ...
            'xLo', 0.17, 'xHi', 0.83, 'win', 0.02, ...
            'qV', 1e-8, 'qW', 1e-12, ...
            'ell', 6, ...
            'dpr', linspace(0.03,0.13,11), ...
            'dprw', linspace(0.025,0.12,11), ...
            'nfr', 40, 'xe0', 0.20, 'v', 0.01, 'b0', 0.55, 'w', 0.30/39);
    case 'hybrid'
        cfg = struct( ...
            'Profile', 'hybrid', ...
            'M', 1024, 'N', 2048, ...
            'alphas', (0.55:0.05:0.85)', ...
            'beta', 0.70, ...
            'A', 1.0, 'sGrid', 8, ...
            'sigA', 0.01, 'sigB', 0.02, ...
            'w0', 0.03, 'w1', 0.28, ...
            'xLo', 0.17, 'xHi', 0.83, 'win', 0.02, ...
            'qV', 1e-8, 'qW', 1e-12, ...
            'ell', 6, ...
            'dpr', linspace(0.03,0.13,11), ...
            'dprw', linspace(0.025,0.12,11), ...
            'nfr', 40, 'xe0', 0.20, 'v', 0.01, 'b0', 0.55, 'w', 0.30/39);
    otherwise
        error('fdedge:config', ...
            "unknown Profile '%s' (expected 'poc'|'beta'|'riesz'|'hybrid')", Profile);
end
% Apply user overrides.
fn = fieldnames(ov);
for k = 1:numel(fn)
    if ~isfield(cfg, fn{k})
        error('fdedge:config', "unknown config field '%s'", fn{k});
    end
    cfg.(fn{k}) = ov.(fn{k});
end
% D9 invariant: the probe window must start outside the Gaussian blur core.
if any(strcmp(cfg.Profile, {'beta','riesz','hybrid'})) && cfg.w0 <= 3*cfg.sGrid/cfg.M
    error('fdedge:winScale', ...
        'w0 = %.4f must exceed 3*sigma_smooth = 3*%d/%d = %.4f (probe window must start outside the Gaussian blur core)', ...
        cfg.w0, cfg.sGrid, cfg.M, 3*cfg.sGrid/cfg.M);
end
end
